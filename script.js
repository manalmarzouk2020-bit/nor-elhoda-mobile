function certStats(){
  const best=getBest();
  let done=0, score=0;
  STORIES.forEach(s=>{ if(best[s.id]!=null){ done++; score+=best[s.id]; } });
  return {done, score, max:STORIES.length*3, total:STORIES.length};
}
function certLevel(score,max){
  const p = max? score/max : 0;
  if(p>=0.9) return '🏆 بطل قصص الأنبياء بامتياز وشرف';
  if(p>=0.7) return '🌟 بطل قصص الأنبياء';
  if(p>=0.5) return '💪 بطل واعد — واصل التقدم';
  return '📖 مثابر جميل — أكمل وتعلم أكثر';
}
