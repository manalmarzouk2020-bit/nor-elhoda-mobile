// ===== تحدي الأسبوع ⏳ (السبت → الجمعة، الهدف 30 نجمة) =====
const WEEK_KEY='nour_weekly';
const WEEK_GOAL=30;
function weekRange(now){
  const d=new Date(now); d.setHours(0,0,0,0);
  const sinceSat=(d.getDay()+1)%7; // السبت=0 ... الجمعة=6
  const start=new Date(d); start.setDate(d.getDate()-sinceSat);
  const end=new Date(start); end.setDate(start.getDate()+6); end.setHours(23,59,59,999);
  return {start,end};
}
function weekId(date){ const s=weekRange(date).start; return s.getFullYear()+'-'+(s.getMonth()+1)+'-'+s.getDate(); }
function getWeekly(){
  const id=weekId(new Date());
  try{
    let w=JSON.parse(localStorage.getItem(WEEK_KEY));
    if(!w || w.weekId!==id){ w={weekId:id, best:{}}; localStorage.setItem(WEEK_KEY, JSON.stringify(w)); }
    return w;
  }catch(e){ return {weekId:id, best:{}}; }
}
function saveWeekly(w){ try{ localStorage.setItem(WEEK_KEY, JSON.stringify(w)); }catch(e){} }
function weeklyScore(kidId){ const w=getWeekly(); const m=w.best[kidId]||{}; return Object.values(m).reduce((a,b)=>a+b,0); }
// تُستدعى عند تصحيح أي اختبار — تعيد true إذا تحسّن مجموع الأسبوع
function updateWeekly(storyId, score){
  const w=getWeekly();
  const kidId=getActiveId();
  if(!w.best[kidId]) w.best[kidId]={};
  const prev=w.best[kidId][storyId]||0;
  if(score>prev){ w.best[kidId][storyId]=score; saveWeekly(w); renderWeekly(); return true; }
  renderWeekly();
  return false;
}
function weeklyWinner(){
  const kids=getKids().map(k=>({k, s:weeklyScore(k.id)}));
  const champs=kids.filter(x=>x.s>=WEEK_GOAL).sort((a,b)=>b.s-a.s);
  return champs.length? champs[0] : null;
}
function renderWeekly(){
  const board=document.getElementById('weeklyBoard'), win=document.getElementById('weeklyWinner');
  if(!board) return;
  const kids=getKids();
  const ranked=[...kids].sort((a,b)=>weeklyScore(b.id)-weeklyScore(a.id));
  board.innerHTML=ranked.map(x=>{
    const s=weeklyScore(x.id);
    const p=Math.min(100, Math.round(s/WEEK_GOAL*100));
    const done=s>=WEEK_GOAL;
    return `<div class="weekly-row ${done?'done':''}">
      <span class="weekly-name">${done?'🏆 ':''}${x.id===getActiveId()?'👈 ':''}${esc(x.name)}</span>
      <div class="weekly-pbar"><span style="width:${p}%"></span></div>
      <span class="weekly-num">${s}/${WEEK_GOAL} ⭐</span>
    </div>`;
  }).join('');
  const w=weeklyWinner();
  if(w && win){
    win.style.display='block';
    win.innerHTML=`🎉🏆 <strong>${esc(w.k.name)}</strong> هو بطل هذا الأسبوع بمجموع <strong>${w.s} نجمة</strong>! صفقوا له 👏👏`;
  } else if(win){ win.style.display='none'; win.innerHTML=''; }
  tickWeeklyTimer();
}
let _lastWeekId=null;
function tickWeeklyTimer(){
  const now=new Date();
  const cur=weekId(now);
  if(_lastWeekId===null){ _lastWeekId=cur; }
  else if(cur!==_lastWeekId){ _lastWeekId=cur; renderWeekly(); return; }
  const el=document.getElementById('weeklyTimer'); if(!el) return;
  const end=weekRange(now).end;
  let s=Math.max(0, Math.floor((end-Date.now())/1000));
  const d=Math.floor(s/86400); s%=86400;
  const h=Math.floor(s/3600), m=Math.floor((s%3600)/60), sec=s%60;
  el.textContent = d>0
    ? `⏳ ينتهي التحدي بعد: ${d} يوم و ${h} ساعة و ${m} دقيقة`
    : `⏳ ينتهي التحدي بعد: ${h} ساعة و ${m} دقيقة و ${sec} ثانية`;
}
